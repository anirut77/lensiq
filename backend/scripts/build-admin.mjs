#!/usr/bin/env node
// backend/scripts/build-admin.mjs — copy the admin shell into backend/admin-dist/ for Workers Static Assets, so the
// back office is served from the Worker's OWN origin (e.g. https://admin.<domain> custom domain on this Worker):
// same-origin API calls, the __Host- session cookie works, and the Worker adds frame-ancestors 'none' +
// X-Frame-Options DENY as real HTTP headers (src/index.js ADMIN_PAGE_HEADERS).
// lensiq-config.js is replaced by a one-liner that points LENSIQ_API_BASE at the page's own origin.
import { copyFileSync, mkdirSync, rmSync, writeFileSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..", "..");
const out = resolve(here, "..", "admin-dist");
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
// attendance-qr.js: the QR encoder (no dependencies) that draws the 2-step verification QR code on the device
// fortune-sources.js: the fortune citation list, shown in the back office only (generated by tools/fortune-sources.mjs)
for (const f of ["admin.js", "admin-orgs.js", "admin.css", "lensiq-api.js", "lensiq-i18n.js", "attendance-qr.js", "fortune-sources.js"]) copyFileSync(join(repo, f), join(out, f));
// round 17 P5: English / Chinese text of the AI Gateway section (lensiq-i18n.js loads en-admin.js on demand)
mkdirSync(join(out, "i18n"), { recursive: true });
for (const f of ["zh-admin.js", "en-admin.js"]) copyFileSync(join(repo, "i18n", f), join(out, "i18n", f));
// the page keeps its <meta> CSP; with the API on the same origin connect-src 'self' is all it needs
const html = readFileSync(join(repo, "admin.html"), "utf8").replace(/connect-src [^;]*;/, "connect-src 'self';");
writeFileSync(join(out, "admin.html"), html);
writeFileSync(join(out, "lensiq-config.js"), "/* generated by backend/scripts/build-admin.mjs — admin served by the API Worker itself */\n" +
  "window.LENSIQ_API_BASE = location.origin;\nwindow.LENSIQ_ANALYTICS = false;\n");
console.log("build-admin: admin shell -> " + out);
