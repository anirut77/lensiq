#!/usr/bin/env node
// tools/device-fit.mjs — "best used on" (owner order 2026-11-14): writes the device line of every sales document listed
// in lensiq-devicefit.js DOCS, and the full table in docs/PAGE-STATUS.md, from the one config (lensiq-devicefit.js).
//
//   node tools/device-fit.mjs           write the blocks (a missing block is inserted after the document's opening
//                                       paragraph: under the H1 for th / th+en / zh, under "# English" for en)
//   node tools/device-fit.mjs --check   write nothing; exit 1 and list the documents that are out of date
//   node tools/device-fit.mjs --table   print the table (Markdown) to stdout
// tests/unit/device-fit.test.js runs --check.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const F = require("../lensiq-devicefit.js");
const D = require("./cat-data.cjs");

const BLOCK = lang => new RegExp("<!-- device-fit:" + lang.replace("+", "\\+") + " [^>]*-->\\n[\\s\\S]*?\\n<!-- /device-fit -->");

/** line index after the first paragraph that follows line `from` (skipping blank lines, and one H2 right after an H1) */
function afterFirstParagraph(lines, from, skipH2) {
  let i = from + 1;
  while (i < lines.length && !lines[i].trim()) i++;
  if (skipH2 && /^## /.test(lines[i] || "")) { i++; while (i < lines.length && !lines[i].trim()) i++; }
  while (i < lines.length && lines[i].trim()) i++;
  return i;
}
function insert(src, lang, block) {
  const lines = src.split("\n");
  const from = lang === "en" ? lines.findIndex(l => l === "# English") : lines.findIndex(l => /^# /.test(l));
  if (from < 0) throw new Error(`no ${lang === "en" ? '"# English"' : "H1"} to insert the ${lang} block under`);
  const at = afterFirstParagraph(lines, from, lang === "en");
  lines.splice(at, 0, "", ...block.split("\n"));
  return lines.join("\n");
}

const basisCell = e => e.basis === "measured" ? `measured (synthetic): ${e.src.doc} — "${e.src.quote[0]}"` : e.src;
/** the full table, in category order, then the platform and other pages */
export function table() {
  const seen = new Set(), rows = [];
  const row = (cat, p) => {
    const e = F.FIT[p], shown = F.catalogueFit(p);
    rows.push(`| ${cat} | \`${p}.html\` | ${e.fit}${shown !== e.fit ? ` (catalogue: ${shown})` : ""} | ${F.REASONS[e.why].en} | ${basisCell(e).replace(/\|/g, "\\|")} |`);
    seen.add(p);
  };
  for (const c of D.CATEGORIES) for (const p of c.pages) if (!seen.has(p)) row(c.n + " " + c.name.en, p);
  for (const p of Object.keys(F.FIT)) if (!seen.has(p)) row("Platform / other", p);
  return ["| Category | Page | Best used on | Reason | Basis |", "|---|---|---|---|---|", ...rows].join("\n");
}
const TABLE_START = "<!-- device-fit table (generated by tools/device-fit.mjs from lensiq-devicefit.js) -->";
const TABLE_END = "<!-- /device-fit table -->";
function tableSection() {
  return TABLE_START + "\n## Best used on (device per page, owner order 2026-11-14)\n\n" +
    "One config: `lensiq-devicefit.js`. computer = best on a computer; tablet = best on a tablet or computer; phone = best on " +
    "a phone; any = any device. On a phone, computer and tablet pages show a short notice (send the link to yourself / " +
    "continue anyway). \"measured (synthetic)\" = headless browser figures from `docs/PHONE-QUALITY.md`, never a real phone; " +
    "no real-phone crash or memory data exists yet. Overview pages are \"any\" and the catalogues show their working pages' value.\n\n" +
    table() + "\n" + TABLE_END;
}

export function run({ check = false } = {}) {
  const stale = [];
  for (const [doc, spec] of Object.entries(F.DOCS)) {
    const file = join(repo, doc);
    const src = readFileSync(file, "utf8");
    let out = src;
    for (const l of spec.langs) {
      const block = F.docBlock(doc, l);
      out = BLOCK(l).test(out) ? out.replace(BLOCK(l), () => block) : insert(out, l, block);
    }
    if (out !== src) { stale.push(doc); if (!check) writeFileSync(file, out); }
  }
  const ps = join(repo, "docs", "PAGE-STATUS.md");
  const src = readFileSync(ps, "utf8");
  const i = src.indexOf(TABLE_START), j = src.indexOf(TABLE_END);
  const out = i >= 0 && j > i ? src.slice(0, i) + tableSection() + src.slice(j + TABLE_END.length) : src.replace(/\n*$/, "\n\n") + tableSection() + "\n";
  if (out !== src) { stale.push("docs/PAGE-STATUS.md"); if (!check) writeFileSync(ps, out); }
  return stale;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--table")) { console.log(table()); process.exit(0); }
  const check = process.argv.includes("--check");
  const stale = run({ check });
  if (check && stale.length) { console.error("device-fit: out of date (run node tools/device-fit.mjs): " + stale.join(", ")); process.exit(1); }
  console.log(check ? "device-fit: all documents current" : `device-fit: wrote ${stale.length} file(s)${stale.length ? ": " + stale.join(", ") : ""}`);
}
