#!/usr/bin/env node
// tools/fortune-caution-pack.mjs — writes the browser rule packs of the "สิ่งที่ควรระวัง" section (owner item 177):
// one fortune-caution-pack-<domain>-<lang>.js per page domain of fortune-caution-core.js DOMAINS and language, holding only the
// rules of that page and the texts of that language (no sources: those stay in the registry), so the files the reader loads
// after accepting the disclaimer stay small (locked T12: <= 30 KB with the core). It also stamps the version V of
// fortune-caution.js with a hash of the core and every pack, so any change to a lazily loaded file changes its ?v=.
//   node tools/fortune-caution-pack.mjs           write the packs and the version
//   node tools/fortune-caution-pack.mjs --check   exit 1 when a pack or the version is out of date (tests/unit/fortune-caution-pack.test.js)
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const LANGS = ["th", "en", "zh"];
const TEXTS = ["mind", "do", "cheer", "luck"];
const KEEP = ["id", "school", "kind", "spans", "polarity", "topic", "trigger", "modern", "status"];
const SHELL = join(repo, "fortune-caution.js");

/** @returns {Record<string, string>} file name -> content */
export function packs() {
  const core = require(join(repo, "fortune-caution-core.js"));
  // the browser does not load the filter: every text goes into a pack only when the filter allows it in every place it can show
  const bad = [];
  for (const r of core.rules()) for (const f of TEXTS) if (r[f]) for (const lang of LANGS) {
    const ctxs = r.kind === "period" ? (r.spans || []).map(span => ({ part: "period", span })) : [{ part: "overall" }];
    for (const ctx of ctxs) { const why = core.check(r[f][lang], f, ctx); if (why) bad.push(`${r.id}.${f}.${lang} (${ctx.span || ctx.part}): ${why}`); }
  }
  if (bad.length) throw new Error("fortune-caution-pack: texts the filter refuses:\n  " + bad.join("\n  "));
  /** @type {Record<string, string>} */
  const out = {};
  for (const domain of Object.keys(core.DOMAINS)) for (const lang of LANGS) {
    const list = core.rules().filter(r => r.domains.includes(domain)).map(r => {
      /** @type {Record<string, any>} */
      const o = { domains: [domain] };
      for (const k of KEEP) if (r[k] !== undefined) o[k] = r[k];
      for (const f of TEXTS) if (r[f]) o[f] = { [lang]: r[f][lang] };
      return o;
    });
    out[`fortune-caution-pack-${domain}-${lang}.js`] = "/* " + `fortune-caution-pack-${domain}-${lang}.js` +
      " — generated by tools/fortune-caution-pack.mjs from fortune-caution-rules-*.js; do not edit. */\n" +
      "(function (w) {\n  var R = " + JSON.stringify(list, null, 1) + ";\n" +
      "  var all = w.LQCautionRules = w.LQCautionRules || [];\n" +
      "  R.forEach(function (r) {\n" +
      "    var o = all.filter(function (x) { return x.id === r.id; })[0];\n" +
      "    if (!o) { all.push(r); return; }\n" +
      "    r.domains.forEach(function (d) { if (o.domains.indexOf(d) < 0) o.domains.push(d); });\n" +
      "    [\"mind\", \"do\", \"cheer\", \"luck\"].forEach(function (f) { if (r[f]) o[f] = Object.assign(o[f] || {}, r[f]); });\n" +
      "  });\n})(window);\n";
  }
  return out;
}

/** version of the lazily loaded files: first 8 hex of sha256(core + packs) @param {Record<string, string>} p */
export function version(p) {
  const h = createHash("sha256").update(readFileSync(join(repo, "fortune-caution-core.js")));
  for (const k of Object.keys(p).sort()) h.update(k).update(p[k]);
  return h.digest("hex").slice(0, 8);
}

const VRE = /var V = "([0-9a-f]{8})";/;
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const p = packs(), v = version(p), check = process.argv.includes("--check");
  const shell = readFileSync(SHELL, "utf8");
  if (!VRE.test(shell)) { console.error("fortune-caution.js has no `var V = \"<8 hex>\";` line"); process.exit(2); }
  const stale = Object.keys(p).filter(f => !existsSync(join(repo, f)) || readFileSync(join(repo, f), "utf8") !== p[f]);
  const vOld = VRE.exec(shell)[1];
  if (check) {
    if (stale.length || vOld !== v) { console.error("out of date: " + stale.join(", ") + (vOld !== v ? " version " + vOld + " -> " + v : "")); process.exit(1); }
    console.log("fortune-caution packs OK (" + Object.keys(p).length + " files, version " + v + ")");
  } else {
    for (const f of stale) writeFileSync(join(repo, f), p[f]);
    if (vOld !== v) writeFileSync(SHELL, shell.replace(VRE, `var V = "${v}";`));
    console.log("wrote " + stale.length + " pack(s); version " + v);
  }
}
