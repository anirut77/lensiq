#!/usr/bin/env node
// tools/helpline.mjs — writes the always-visible help line (owner order 2026-11-12) into every fortune page as static
// HTML, so it shows without JavaScript: one <aside id="lqHelpTop"> right before <main> and one <aside id="lqHelpEnd">
// as the last child of <main>. The Thai text comes from LQFortuneCrisis.HELP (fortune-crisis.js), the canonical
// wording; English / Chinese are in i18n/{en,zh}-common.js under help.line.* (tests/unit/fortune-helpline.test.js
// checks that all three agree). Numbers and hours: docs/CRISIS-RESOURCES.md (verified from official sources only).
// cat-fortune.html is generated by tools/cat-pages.mjs, which uses snippet() from here.
// Owner order 2026-11-14 (Part B): every help number is the shared tap-to-call component (lensiq-helpline.js). This tool
// also re-draws every static component in CALL_PAGES (medicine, nutrition, terms and the fortune pages) from
// LQHelpline.html(), keeping its language, extra class and compact form, so no static copy can drift from the component.
//
//   node tools/helpline.mjs           write the line into the pages listed in PAGES
//   node tools/helpline.mjs --check   write nothing; exit 1 and list the pages (and i18n help.line.* entries) out of date
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const { HELP } = require("../fortune-crisis.js");
const LQH = require("../lensiq-helpline.js");

/** the hand-written fortune pages (cat-fortune.html comes from tools/cat-pages.mjs) */
export const PAGES = ["fortune", "faceread", "palm", "horoscope", "tarot", "iching", "bazi", "taksa", "lek7", "numbers", "fengshui",
  "dream", "zodiac", "astro", "lifegraph", "planner", "luckycolor", "report"];

const esc = s => String(s).replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

/** one component's HTML on several lines (each at most ~150 characters): breaks only before an opening tag, so no text
 *  node gains whitespace and no tag is split @param {string} h @param {string} indent */
export function wrapCall(h, indent) {
  const parts = h.split(/(?=<(?:span|a|svg|small|path)\b)/), lines = [];
  let cur = "";
  for (const t of parts) {
    if (cur && (indent.length + 2 + cur.length + t.length > 150)) { lines.push(cur); cur = t; } else cur += t;
  }
  if (cur) lines.push(cur);
  return lines.map((l, i) => (i ? indent + "  " : "") + l).join("\n");
}

/** pages whose static tap-to-call components are re-drawn from the component (besides the fortune pages) */
export const CALL_PAGES = ["medicine", "nutrition", "terms"];

/** the static help line (Thai, with data-i18n keys) @param {"lqHelpTop"|"lqHelpEnd"} id @param {string} [indent] */
export function snippet(id, indent = "") {
  const T = HELP.th;
  return [
    `<aside class="lq-helpline" id="${id}" role="note" aria-label="${esc(T.label)}" data-i18n-attr="aria-label:help.line.label">`,
    ...HELP.tel.map(n => "  " + wrapCall(LQH.html(n, { lang: "th", cls: "lq-helpline-tel", compact: n !== "1323" }), indent + "  ")),
    `  <span class="lq-helpline-note" data-i18n="help.line.note">${esc(T.note)}</span>`,
    `</aside>`,
  ].map(l => indent + l).join("\n");
}

/** every static component (<span class="lq-call" data-lq-call="id">…</span>) re-drawn by LQHelpline.html() with the same
 *  language (Thai = has data-i18n keys or Thai letters; Chinese = CJK letters; else English), extra class and compact form
 *  @param {string} html */
export function redrawCalls(html) {
  let out = "", i = 0;
  const open = /<span class="lq-call" data-lq-call="([^"]+)">/g;
  let m;
  while ((m = open.exec(html))) {
    const re = /<span\b|<\/span>/g; re.lastIndex = m.index;
    let depth = 0, x;
    while ((x = re.exec(html))) { depth += x[0][1] === "/" ? -1 : 1; if (depth === 0) break; }
    if (!x) throw new Error("unbalanced lq-call component");
    const block = html.slice(m.index, re.lastIndex), id = m[1];
    const btn = (/<span class="lq-call-t"[^>]*>([^<]*)</.exec(block) || [])[1] || "";
    const lang = /data-i18n=/.test(block) || /[\u0E00-\u0E7F]/.test(btn) ? "th" : /[\u3400-\u9FFF]/.test(btn) ? "zh" : "en";
    const cls = ((/<a class="lq-call-btn([^"]*)"/.exec(block) || [])[1] || "").trim();
    const compact = !/class="lq-call-sub"/.test(block);
    const before = html.slice(html.lastIndexOf("\n", m.index) + 1, m.index), indent = (/^[ \t]*/.exec(before) || [""])[0];
    // a component after text on the same line starts on its own line (keeps every line short; the line break is whitespace)
    const lead = before.trim() ? html.slice(i, m.index).replace(/[ \t]+$/, "") + "\n" + indent + "  " : html.slice(i, m.index);
    out += lead + wrapCall(LQH.html(id, { lang, cls: cls || undefined, compact, keys: lang === "th" && (/data-i18n=/.test(block) || !btn) }), indent);
    i = re.lastIndex; open.lastIndex = re.lastIndex;
  }
  return out + html.slice(i);
}

const OLD = /^[ \t]*<aside class="lq-helpline" id="lqHelp(?:Top|End)"[\s\S]*?<\/aside>\n/gm;
/** the page with both lines in place (any older copy replaced) @param {string} html */
export function applyTo(html) {
  let h = html.replace(OLD, "");
  const main = h.search(/^[ \t]*<main\b/m);
  if (main < 0) throw new Error("no <main> at the start of a line");
  h = h.slice(0, main) + snippet("lqHelpTop") + "\n" + h.slice(main);
  const end = h.lastIndexOf("</main>");
  const lineStart = h.lastIndexOf("\n", end) + 1;
  if (h.slice(lineStart, end).trim()) throw new Error("</main> is not on its own line");
  return h.slice(0, lineStart) + snippet("lqHelpEnd", "  ") + "\n" + h.slice(lineStart);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check"), stale = [];
  for (const p of PAGES) {
    const f = join(repo, p + ".html"), html = readFileSync(f, "utf8"), out = redrawCalls(applyTo(html));
    if (out === html) continue;
    stale.push(p + ".html");
    if (!check) writeFileSync(f, out);
  }
  for (const p of CALL_PAGES) {
    const f = join(repo, p + ".html"), html = readFileSync(f, "utf8"), out = redrawCalls(html);
    if (out === html) continue;
    stale.push(p + ".html");
    if (!check) writeFileSync(f, out);
  }
  // every dictionary that carries call.* must say exactly the component's text
  for (const l of ["en", "zh"]) {
    for (const f of readdirSync(join(repo, "i18n")).filter(x => x.startsWith(l + "-") && x.endsWith(".js"))) {
      const src = readFileSync(join(repo, "i18n", f), "utf8");
      for (const m of src.matchAll(/"call\.(\w+)\.(btn|sub|org)":\s*("(?:[^"\\]|\\.)*")/g)) {
        if (!LQH.LINES[m[1]] || JSON.parse(m[3]) !== LQH.LINES[m[1]][l][m[2]]) stale.push("i18n/" + f + " call." + m[1] + "." + m[2]);
      }
    }
  }
  // every dictionary that carries help.line.* (common + page dictionaries a page test needs) must say exactly HELP
  for (const l of ["en", "zh"]) {
    for (const f of readdirSync(join(repo, "i18n")).filter(x => x.startsWith(l + "-") && x.endsWith(".js"))) {
      const src = readFileSync(join(repo, "i18n", f), "utf8");
      for (const m of src.matchAll(/"help\.line\.(\w+)":\s*("(?:[^"\\]|\\.)*")/g)) if (JSON.parse(m[2]) !== HELP[l][m[1]]) stale.push("i18n/" + f + " help.line." + m[1]);
    }
  }
  if (check && stale.length) { console.error("help line out of date (run node tools/helpline.mjs): " + stale.join(", ")); process.exit(1); }
  console.log(check ? "help line: all " + PAGES.length + " pages current" : "help line written: " + (stale.join(", ") || "nothing to change"));
}
