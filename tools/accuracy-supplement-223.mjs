#!/usr/bin/env node
// tools/accuracy-supplement-223.mjs — owner decision 223: page texts with numbers that the base snapshot
// (docs/tech-sheets/ORIGINAL-FIGURES-223.json, tools/accuracy-snapshot-223.mjs) did not catch because they carry no
// "%", "n =" or source tag (found by the re-lock review: gate.acc.l7 and a few more). Reads the base commit with git,
// so the texts are the originals, unchanged. Output: docs/tech-sheets/SUPPLEMENT-223.json, read by tools/tech-sheets.mjs.
//   node tools/accuracy-supplement-223.mjs           write the file
//   node tools/accuracy-supplement-223.mjs --check   exit 1 when it is out of date
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const L = require(join(repo, "tests", "unit", "accuracy-removal-223.lib.js"));
export const BASE = "ecb783b6";
const OUT = "docs/tech-sheets/SUPPLEMENT-223.json";
const git = f => { try { return execFileSync("git", ["show", `${BASE}:${f}`], { cwd: repo, encoding: "utf8", maxBuffer: 1e8 }); } catch { return null; } };

function baseDict() {
  const out = { en: {}, zh: {} };
  for (const f of execFileSync("git", ["ls-tree", "--name-only", BASE, "i18n/"], { cwd: repo, encoding: "utf8" }).split("\n").filter(f => /^i18n\/(en|zh)-.*\.js$/.test(f))) {
    const win = { LQI18N_Q: [], LQI18N_RT: [] };
    try { vm.runInNewContext(git(f), { window: win, document: undefined, console }); } catch { continue; }
    for (const p of win.LQI18N_Q) for (const l of ["en", "zh"]) if (p && p[l]) for (const [k, v] of Object.entries(p[l])) if (!(k in out[l])) out[l][k] = String(v);
  }
  return out;
}

export function supplement() {
  const snap = JSON.parse(readFileSync(join(repo, "docs/tech-sheets/ORIGINAL-FIGURES-223.json"), "utf8"));
  const known = new Set(snap.entries.flatMap(e => [e.th, e.en, e.zh, e.text]).concat(snap.catData.flatMap(e => [e.th, e.en, e.zh])).filter(Boolean).map(L.squash));
  const D = baseDict(), entries = [];
  for (const f of L.customerFiles().filter(f => f.endsWith(".html"))) {
    const base = git(f);
    if (!base) continue;
    const now = existsSync(join(repo, f)) ? readFileSync(join(repo, f), "utf8") : "";
    const nowKeys = new Map(L.elementTexts(now).map(e => [e.key, e.text]));
    for (const e of L.elementTexts(base)) {
      if (!/\d/.test(e.text) || nowKeys.get(e.key) === e.text || known.has(L.squash(e.text))) continue;
      if (/VAT|บาท|฿/.test(e.text)) continue; // prices are not figures and stay on the pages
      entries.push({ file: f, key: e.key, th: e.text, en: D.en[e.key] || "", zh: D.zh[e.key] || "" });
    }
  }
  return { $comment: `Owner decision 223: original page texts with numbers (base ${BASE}) not in ORIGINAL-FIGURES-223.json, ` +
    `changed or removed by 223. Generated by tools/accuracy-supplement-223.mjs; never edited by hand.`, base: BASE, entries };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const s = JSON.stringify(supplement(), null, 1) + "\n";
  const cur = existsSync(join(repo, OUT)) ? readFileSync(join(repo, OUT), "utf8") : "";
  if (process.argv.includes("--check")) { if (cur !== s) { console.error(`${OUT} is out of date (run node tools/accuracy-supplement-223.mjs)`); process.exit(1); } console.log(`${OUT} up to date`); }
  else { writeFileSync(join(repo, OUT), s); console.log(`${OUT}: ${JSON.parse(s).entries.length} entries`); }
}
