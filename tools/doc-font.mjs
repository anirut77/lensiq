// tools/doc-font.mjs — writes backend/src/doc-font.js: the self-hosted Prompt font (vendor/fonts/prompt, OFL 1.1) as
// inline @font-face rules for the printed quotation / invoice / receipt (owner decision 161, 2026-11-19).
// Why: the document used to name "Sarabun" / "Noto Sans Thai", which no page ships, so Thai fell back to the printing
// machine's own font. On Linux that is TLWG (Loma, Garuda …) and on many Thai office PCs TH Sarabun New; their tone-mark
// variants are encoded at U+F700–U+F71A in the font's cmap, and Chrome's PDF ToUnicode then carries those Private Use
// codes (copy / paste, search and screen readers read them). Prompt has no PUA code points, and an inline font is the
// same on every machine and inside the document's own CSP (font-src data:).
//   node tools/doc-font.mjs          regenerate
//   node tools/doc-font.mjs --check  exit 1 if backend/src/doc-font.js does not match the vendor files
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "backend", "src", "doc-font.js");
// unicode-range values as in styles.css (Google Fonts subsets); 400 for text, 700 for headings / totals (600 maps to 700)
const RANGES = {
  thai: "U+02D7,U+0303,U+0331,U+0E01-0E5B,U+200C-200D,U+25CC",
  latin: "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD"
};
const rules = [];
for (const w of [400, 700]) for (const sub of ["thai", "latin"]) {
  const b64 = readFileSync(join(ROOT, "vendor", "fonts", "prompt", `prompt-${w}-${sub}.woff2`)).toString("base64");
  rules.push(`@font-face{font-family:LQDoc;font-style:normal;font-weight:${w};font-display:block;src:url(data:font/woff2;base64,${b64}) format("woff2");unicode-range:${RANGES[sub]}}`);
}
const src = `// @ts-check
// backend/src/doc-font.js — GENERATED by tools/doc-font.mjs from vendor/fonts/prompt (Prompt, SIL OFL 1.1, see
// vendor/fonts/prompt/OFL.txt). Do not edit by hand. Inline @font-face rules for the printed seller documents, so Thai
// never falls back to a machine font whose tone-mark glyphs map to U+F700–U+F71A in the PDF (owner decision 161).
export const DOC_FONT_FAMILY = "LQDoc";
export const DOC_FONT_CSS = ${JSON.stringify(rules.join("\n"))};
`;
if (process.argv.includes("--check")) {
  let cur = "";
  try { cur = readFileSync(OUT, "utf8"); } catch { /* missing */ }
  if (cur !== src) { console.error("backend/src/doc-font.js is out of date: run node tools/doc-font.mjs"); process.exit(1); }
  console.log("doc-font: up to date");
} else { writeFileSync(OUT, src); console.log("wrote backend/src/doc-font.js (" + src.length + " bytes)"); }
