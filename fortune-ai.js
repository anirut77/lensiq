  function explainTerms(sections) {
    for (const [re0, term, gloss] of GLOSSARY) {
      const re = new RegExp(re0.source, "g");
      let done = false;
      for (const s of sections) {
        if (done) break;
        s.paragraphs = s.paragraphs.map(p => {
          if (done) return p;
          if (p.indexOf(gloss) >= 0) { done = true; return p; }
          re.lastIndex = 0;
          for (let m; (m = re.exec(p));) {
            const before = p.slice(0, m.index);
            if ((before.match(/[(（]/g) || []).length > (before.match(/[)）]/g) || []).length) continue; // อยู่ในวงเล็บ
            let end = m.index + term.length;
            const after = p.slice(end);
            if (/^\s*[(（]|^\s*(?:คือ|หมายถึง|ซึ่งคือ)/.test(after)) { done = true; return p; } // มีคำอธิบายอยู่แล้ว
            // วางวงเล็บที่รอยต่อคำที่ชัด (ช่องว่าง/ท้ายข้อความ) ภายใน 6 ตัวอักษร เช่น "ปีชงเต็ม (…)", "ลัคนากรกฎ (…)"
            const tail = /^[\u0E00-\u0E7F]{0,6}(?:\s\d+)?(?=\s|$)/.exec(after);
            if (!tail) continue;
            end += tail[0].length;
            const out = p.slice(0, end) + " (" + gloss + ")" + p.slice(end);
            // คำอธิบายในวงเล็บต้องไม่ทำให้เกิด "X (…) เชื่อกันว่า X…" (ซ้ำชื่อหลังวงเล็บ) — ถ้าเกิด ข้ามตำแหน่งนี้
            if (labelEcho(out) && !labelEcho(p)) continue;
            done = true;
            return out;
          }
          return p;
        });
      }
    }
  }

