    const cap = (s, n, keepLast) => { while (s && len() > max && s.paragraphs.length > n) s.paragraphs.splice(keepLast ? s.paragraphs.length - 2 : s.paragraphs.length - 1, 1); };
    cap(sections.find(s => s.id === "advice"), 2);
