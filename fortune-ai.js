  // ด่านสุดท้ายของทุกประโยค: ไวยากรณ์ (grammarIssues), ซ้ำชื่อ, งบประโยคกลาง ๆ, ขั้วความหมายที่ขัดกัน, หัวข้อไม่ตรง
  function vet(ctx, s) {
    s = tidy(s);
    if (!s || !isSafe(s)) return null;
    if (grammarIssues(s).length) { ctx.rejected = (ctx.rejected || 0) + 1; return null; }
    if (!ctx.names) ctx.names = ctx.F.items.map(it => it.label).concat(ctx.F.items.map(it => it.short).filter(Boolean));
    if (tautology(s, ctx.names) || labelEcho(s)) { ctx.rejected = (ctx.rejected || 0) + 1; return null; }
    const fill0 = (s.match(FILLER_RE) || []).length;
    if (fill0 && (ctx.fillers || 0) + fill0 > FILLER_BUDGET) return null;
    const poles = polesOf(s);
    if (poles.some(([id, p]) => ctx.poles[id] === 1 - p)) return null;
    if (ctx.sec && (loveOnlyIn(s, ctx.sec) || (ctx.sec === "money" && s.split(" ").some(cl => cl.length >= 20 && TOPIC_LEX.love.test(cl) && !TOPIC_LEX.money.test(cl))))) return null;
    const ak = adviceKeysOf(s), tr = traitsOf(s);
    if (ak.some(k => ctx.adviceKeys.has(k))) return null;
    if (tr.some(k => ctx.traits.has(TRAIT_OPP[k]))) return null;
    const n = normSentence(s);
    if (!n) return null;
    const bg = bigrams(n);
    for (const a of ctx.accepted) {
      if (a.n === n) return null;
      if (n.length >= 12 && a.n.length >= 12 && dice(a.bg, bg) >= 0.82) return null;
    }
    ctx.accepted.push({ n, bg });
    ctx.fillers = (ctx.fillers || 0) + fill0;
    for (const [id, p] of poles) ctx.poles[id] = p;
    for (const k of ak) ctx.adviceKeys.add(k);
    for (const k of tr) ctx.traits.add(k);
    return s;
  }

  // secId: หัวข้อที่จะวาง — ข้ามเนื้อความที่พูดถึงหัวข้ออื่นล้วน ๆ (เช่น คำแนะนำเรื่องคนรักในหัวข้อการเงิน)
  /* เนื้อความที่ซ้ำกับเนื้อความที่ใช้ไปแล้ว (มีช่วงข้อความยาว ≥ 18 ตัวอักษรตรงกัน) — เช่นคำแนะนำเดียวกันที่อยู่ทั้งในคลังของสิ่งที่พบและใน tips
     "จัดเวลาพักใจสั้น ๆ ระหว่างวัน เช่น …" กับ "จัดเวลาพักใจสั้น ๆ ระหว่างวัน และพก…" ถือว่าซ้ำ */
  const coreOf = m => String(m).replace(/[\s​.,!?;:"'()\-–—…]/g, "");
  const OVL = 18;
  function overlapsUsed(ctx, m) {
    const c = coreOf(m);
    if (c.length < OVL) return false;
    for (let i = 0; i + OVL <= c.length; i += 3) if (ctx.cores.has(c.substr(i, OVL))) return true;
    return false;
  }
  const markUsed = (ctx, m) => { ctx.used.add(m); const c = coreOf(m); for (let i = 0; i + OVL <= c.length; i++) ctx.cores.add(c.substr(i, OVL)); };
  function pickMeaning(ctx, it, keys, secId) {
    const pool = [];
    for (const k of keys) { const arr = it.meanings[k]; if (Array.isArray(arr)) for (const m of arr) { const c = cleanMeaning(m); if (c && !ctx.used.has(c) && isSafe(c) && !(secId && (offTopic(c, secId) || loveOnlyIn(c, secId))) && !overlapsUsed(ctx, c)) pool.push(c); } }
    if (!pool.length) return null;
    // เลี่ยงสำนวนที่ขึ้นต้นด้วยคำนำหน้าที่ใช้ไปแล้วในคำทำนายนี้
    const fresh = pool.filter(c => { const sp = splitLead(c); return !sp || !ctx.leads.has(sp.lead); });
    const m = pick(ctx.r, fresh.length ? fresh : pool); markUsed(ctx, m); return m;
  }
  const hasKeys = (it, keys) => keys.some(k => Array.isArray(it.meanings[k]) && it.meanings[k].length);

  // เลือกกรอบแรกที่ยังไม่เกินงบจากรายการ (สุ่มลำดับ)
  const firstUnder = (ctx, list) => shuffle(ctx.r, list).find(f => under(ctx, f)) || list[0];
  const NEG_FRAMES = ["{LEV}เตือนเบา ๆ ว่า{M}", "{LEV}ฝากข้อคิดไว้ว่า{M}", "^ตามคำแนะนำของ{LE} {M}"];

  // สร้างประโยคจากสิ่งที่พบ 1 รายการ (+ คืนค่าว่าเติมคำเชื่อมได้หรือไม่)
  function itemSentence(ctx, it, m, mode) {
    const r = ctx.r;
    let R0 = null;
    const done = (text, noConn) => {
      // "X บ่งบอกว่า X…" → ไม่ใช้กริยารายงาน และตัดวงเล็บ/หลักฐานที่ซ้ำกับเนื้อความ: "จาก X …" / "ส่วน X …"
      if (R0 && text !== m && labelEcho(tidy(text), true)) {
        const nm = R0.name.replace(/\s*[(（][^)）]*[)）]/g, "").trim() || R0.name;
        text = (R0.first ? "จาก" : "ส่วน") + nm + " " + m; noConn = true;
      }
      spend(ctx, text); return { text, noConn, sub: true, claim: { kind: "item", ids: [it.id], sec: ctx.sec } };
    };
    // ความหมายที่ขึ้นต้นด้วยชื่อสิ่งที่พบอยู่แล้ว (หรือคลังระบุว่าเป็นประโยคสมบูรณ์) → ใช้ตามนั้น ไม่ต้องเอ่ยชื่อซ้ำ
    if (it.plain || m.indexOf(it.label) === 0 || (it.short && m.indexOf(it.short) === 0)) {
      ctx.fullShown.add(it.id); ctx.mentioned.add(it.id); ctx.lastItem = it.id;
      return done(m, !!it.plain);
    }
    const wantEv = mode === "first" && r() < 0.8;
    R0 = ref(ctx, it, { evidence: wantEv });
    const LE = R0.name + (R0.ev ? " (" + R0.ev + ")" : "");
    const LEV = LE + (R0.ev ? " " : "");
    const L = mode === "more" ? (r() < 0.6 ? pronounOf(it.short || it.label) : R0.name) : R0.name;
    ctx.mentioned.add(it.id);
    const prevItem = ctx.lastItem; ctx.lastItem = it.id;
    let sp = splitLead(m);
    // คำแนะนำที่มีคำนำหน้า ("ด้านการเงิน ลอง…") → ตัดคำนำหน้า แล้วใช้กรอบคำแนะนำ
    if (sp && isImperative(sp.rest)) { m = sp.rest; sp = null; }
    const hedgy = HEDGY.test(m);
    const V = () => (hedgy ? ctx.P() : ctx.V());
    // ความหมายมีคำนำหน้าของตัวเอง → ใช้กรอบเบา ๆ ไม่ซ้อนสองชั้น
    if (sp) {
      const fresh = !ctx.leads.has(sp.lead);
      // ใช้คำนำหน้าได้ไม่เกิน 1 ครั้งต่อหัวข้อ และไม่ซ้ำทั้งคำทำนาย นอกนั้นตัดทิ้ง
      if (sp.kind !== "drop" && fresh && !ctx.secLead && !(sp.kind === "topic" && leadTopic(sp.lead) === ctx.sec) && r() < 0.75 && roleOf(sp.rest) === "clause" && !OWN_REPORT.test(sp.rest) && !mentions(sp.rest, it)) {
        ctx.leads.add(sp.lead); ctx.secLead = 1;
        if (sp.kind === "wa") {
          let f = ctx.wa(); if (/^\^ด้วย/.test(f) && /^เกิด/.test(R0.name)) f = "{LEV}ทำให้{M}";
          const noConn = f[0] === "^";
          return done(fill(noConn ? f.slice(1) : f, ctx.vars({ LE, LEV, M: m })), noConn);
        }
        return done(fill(ctx.hoist().replace(/^\^/, ""), ctx.vars({ LEAD: sp.lead, LE, LEV, V: V(), M: sp.rest })), true);
      }
      m = sp.rest;
    }
    // คำแนะนำ ("ลอง…", "เปิดบัญชี…", "อย่า…") ต่อหลังกรอบความเชื่อ ("เชื่อกันว่า/บ่งบอกว่า") ไม่ได้ ต้องใช้กรอบคำแนะนำ
    if (isImperative(m)) {
      const neg = /^(?:คุณ)?อย่า/.test(m);
      const f = neg ? firstUnder(ctx, NEG_FRAMES) : drawB(ctx, ctx.imp, IMP_FRAMES.length) || "^ตามคำแนะนำของ{LE} {M}";
      const standalone = f[0] === "^";
      const M = neg ? m.replace(/^คุณ/, "") : standalone ? m.replace(/^ควร/, "คุณควร") : bareAdvice(m);
      return done(fill(standalone ? f.slice(1) : f, ctx.vars({ LE, LEV, M })), standalone);
    }
    /* ---- ช่องตามบทบาททางไวยากรณ์ ---- */
    // เนื้อความที่เอ่ยชื่อสิ่งที่พบเอง ("เคล็ดลับสำหรับธาตุไฟคือ…") → ใช้ตามคลัง ไม่ครอบด้วย "ธาตุไฟแสดงว่า…" (กันซ้ำชื่อ/กริยารายงานซ้อน)
    const core = nameCore(it.short || it.label);
    if (core.length >= 3 && m.indexOf(core) >= 0 && !/^ไพ่ใบนี้/.test(m)) return done(m, false);
    // "ไพ่ใบนี้…" (สรรพนามไม่มีที่อ้าง) → ใช้ชื่อไพ่เป็นประธานแทน
    if (/^(?:ไพ่ใบนี้|ใบนี้)/.test(m)) return done(LEV.trim() + " " + m.replace(/^(?:ไพ่ใบนี้|ใบนี้)\s*/, ""), false);
    const role = roleOf(m);
    // กริยาวลีที่ประธานคือสิ่งที่พบ: "{ชื่อ}ช่วยให้…" (ไม่ใช่ "{ชื่อ}บ่งบอกว่าช่วยให้…")
    if (role === "vpItem") return done(LEV + m, false);
    // นามวลี/คำคุณศัพท์ลอย ๆ: "{ชื่อ}สื่อถึงความมั่นคง"
    if (role === "noun" || role === "adjective") return done(LEV + (r() < 0.5 ? "สื่อถึง" : "เน้นเรื่อง") + asNoun(m), false);
    // กริยาวลีที่ประธานคือผู้ถูกทำนาย → เติมประธาน "คุณ" ให้เป็นประโยคสมบูรณ์ก่อนวางหลัง "…ว่า"
    if (role === "vpPerson") m = "คุณ" + m;
    const cond = COND_START.test(m);
    // ความหมายที่มีกริยารายงาน/ภาพบรรยายของตัวเอง ("…บอกว่า…", "ภาพราชินี…สะท้อน…") → วางชื่อไว้หน้าเฉย ๆ ไม่ใส่ "บ่งบอกว่า" ซ้อน
    if (!cond && (SELF_SAYS.test(m) || /^ภาพ/.test(m) || OWN_REPORT.test(m))) {
      const f = R0.first ? pick(r, SELF_FIRST) : pick(r, SELF_NEXT);
      return done(fill(f, ctx.vars({ LE, L, M: m })), true);
    }
    let frame;
    if (mode === "first") {
      for (let k = 0; k < 4; k++) { frame = drawB(ctx, ctx.first, FIRST_FRAMES.length) || "{LEV}{V}{M}"; if (!NEEDS_GROUP.test(frame) || (it.group && it.group !== it.label && it.label.indexOf(it.group) !== 0)) break; frame = "{LEV}{V}{M}"; }
    } else {
      // กรอบที่ไม่เอ่ยชื่อ ใช้ได้เฉพาะเมื่อประโยคก่อนหน้าพูดถึงสิ่งเดียวกัน ไม่งั้นผู้อ่านจะไม่รู้ว่าหมายถึงอะไร
      for (let k = 0; k < 4; k++) { frame = (mode === "more" ? drawB(ctx, ctx.more, MORE_FRAMES.length) : drawB(ctx, ctx.next, NEXT_FRAMES.length)) || "^ส่วน{L} {H}{M}"; if (/\{L/.test(frame) || prevItem === it.id) break; }
      if (!/\{L/.test(frame) && prevItem !== it.id) frame = "^ส่วน{L} {H}{M}";
    }
    if (!R0.first && /\{G\}/.test(frame)) frame = "{LEV}{V}{M}";
    const noConn = frame[0] === "^";
    const plainV = hedgy || cond;
    const linkSlot = /\{LE\} \{H\}/.test(frame);
    const CV = () => firstUnder(ctx, COND_VERBS);
    const H = plainV ? (linkSlot ? (cond ? CV() : ctx.P()) : "") : linkSlot ? ctx.LK() : ctx.H();
    const text = fill(noConn ? frame.slice(1) : frame, ctx.vars({ LE, LEV, L, PV: /\{PV\}/.test(frame) ? ctx.P() : "", G: it.group, H, V: /\{V\}/.test(frame) ? (cond ? CV() : V()) : "", M: m }));
    return done(text, noConn);
  }

  function withConnector(ctx, s) {
    // "ที่น่าสนใจคือ ว่ากันว่า…" / "ข้อดีคือ ถ้า…" อ่านสะดุด → เลี่ยงคำเชื่อมที่ลงท้ายด้วย "คือ" เมื่อประโยคขึ้นต้นด้วยคำออกตัว/เงื่อนไข
    const awkward = c => /คือ$/.test(c) && (STRIP_PREFIX.some(p => s.indexOf(p) === 0) || COND_START.test(s) || /^[^\s]{0,40}คือ/.test(s));
    for (let k = 0; k < 6; k++) {
      const c = ctx.conn();
      if (c === ctx.lastConn || !under(ctx, c) || awkward(c)) continue;
      ctx.lastConn = c; spend(ctx, c);
      return c + " " + s;
    }
    return s;
  }

  // แบ่งย่อหน้า 2–4 ประโยค (กรองประโยคซ้ำก่อนแบ่ง เพื่อไม่ให้เหลือย่อหน้าประโยคเดียว); ประโยคที่ 2 เป็นต้นไปอาจเติมคำเชื่อม
  // ctx.lastSub = จำนวนประโยคเนื้อหา (ไม่นับคำเกริ่น/คำปิด) ที่ผ่านการกรอง, ctx.lastSubText = ข้อความของประโยคเหล่านั้น
  function paragraphs(ctx, list) {
    const r = ctx.r, out = [];
    const ok = [];
    for (const u of list) {
      const s = vet(ctx, u.text);
      if (!s) continue;
      ok.push(Object.assign({}, u, { text: s }));
      if (u.claim) ctx.claims.push(Object.assign({ text: s }, u.claim));
    }
    ctx.lastSub = ok.filter(u => u.sub).length;
    ctx.lastSubText = ok.filter(u => u.sub).map(u => u.text);
    let i = 0;
    while (i < ok.length) {
      let size = 2 + Math.floor(r() * 3);
      const left = ok.length - (i + size);
      if (left === 1) size = size < 4 ? size + 1 : size - 1;
      const chunk = ok.slice(i, i + size);
      const parts = chunk.map((u, j) => {
        let s = u.text;
        const afterIntro = j > 0 && chunk[j - 1].fixed && !chunk[j - 1].sub;
        if (j > 0 && !afterIntro && !u.noConn && !u.fixed && r() < 0.3) s = tidy(withConnector(ctx, s));
        ctx.all.push(s);
        return s;
      });
      out.push(parts.join(" "));
      i += size;
    }
    return out;
  }

