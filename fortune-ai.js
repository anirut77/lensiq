  const MAX_FACTS_BYTES = 19 * 1024; // เซิร์ฟเวอร์รับไม่เกิน 20KB
  const byteLen = s => (typeof TextEncoder !== "undefined" ? new TextEncoder().encode(s).length : unescape(encodeURIComponent(s)).length);
