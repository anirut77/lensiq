  KB.byId = {}; CARDS.forEach(function (c) { KB.byId[c.id] = c; });
  /* ===================== ตัวขยายสำนวน ===================== */
  var TOPIC_KEYS = ["general", "love", "work", "money"];
  var VERB_KW = /^(?:ลง|ขอ|ปิด|ปล่อย|เริ่ม|รับ|ให้|ทำ|เปิด|หยุด|รอ(?!บ)|พัก|ฟัง|มอง|ค้นหา|ตั้ง|แบ่ง|ยอม|ก้าว|ทบทวน|สร้าง|เดิน|ช่วย|เรียน|ดูแล|รักษา|เก็บ|ใช้|ทุ่ม|ตัดสิน|วาง|ส่ง|เลือก|ยืน|ละ|ฝ่า|ข้าม|หนี|ถอย|รื้อ|ฟื้น|เติม|แสวง|ไล่|ยึด|กล้า)/;
  var ADJ_KW = /^(?:ช่าง|ใจ|เก่ง|ขี้|มั่น(?!คง)|อ่อน|อดทน|ซื่อ|รอบคอบ|ละเอียด|ยืดหยุ่น|สุขุม|อบอุ่น|จริงใจ|ร่าเริง|มุ่งมั่น|เมตตา|ขยัน|สงบ|สดใส|เข้มแข็ง)/;
  function nounKw(k) { return /^(?:ความ|การ|พลัง)/.test(k) ? k : VERB_KW.test(k) ? "การ" + k : ADJ_KW.test(k) ? "ความ" + k : k; }
  function fillT(t, v) { return t.replace(/\{(\w+)\}/g, function (_, k) { return v[k] != null ? v[k] : ""; }); }
  /** card.phr = { u: {general:[≥3], ...}, r: {...}, advice: [≥3] } — ข้อความเดิมอยู่ลำดับแรกเสมอ */
  CARDS.forEach(function (c, i) {
    // คำสำคัญเข้าช่องที่ต้องการ "นามวลี" (พลังของ{K1}, นำ{K1}มาใช้) — กริยาวลีเติม "การ" คำคุณศัพท์เติม "ความ"
    // และ K1 ต้องไม่ใช่ชื่อไพ่เอง (กัน "การเปลี่ยนผ่าน … วางน้ำหนักไว้ที่การเปลี่ยนผ่าน")
    var kw = c.keywords.map(nounKw).filter(function (k) { return k !== (c.id === "m13" ? "การเปลี่ยนผ่าน" : c.th); });
    var v = { IMG: IMG[c.id], K1: kw[0], K2: kw[1 + (i % (kw.length - 1))] };
    var ph = { u: {}, r: {}, advice: [c.advice] }, tid = { u: {}, r: {}, advice: [null, "a" + (i % 4), "a" + ((i + 1) % 4)] };
    ["u", "r"].forEach(function (o, oi) {
      TOPIC_KEYS.forEach(function (tp) {
        var pool = TPL[o][tp], a = (i + oi) % pool.length, b = (i + oi + 2) % pool.length;
        ph[o][tp] = [(o === "u" ? c.upright : c.reversed)[tp], fillT(pool[a], v), fillT(pool[b], v)];
        tid[o][tp] = [null, o + tp + a, o + tp + b];
      });
    });
    ph.advice.push(fillT(TPL.advice[i % 4], v), fillT(TPL.advice[(i + 1) % 4], v));
    c.phr = ph; c.phrTpl = tid; // phrTpl = รหัสกรอบของแต่ละสำนวน (null = ข้อความเดิม) ใช้กันกรอบซ้ำข้ามไพ่ในคำทำนายเดียว
  });
  /** ชื่อไพ่สำหรับข้อความทำนาย — ไพ่ XIII ใช้ชื่อ "การเปลี่ยนผ่าน" เพื่อสื่อความหมายเชิงสัญลักษณ์ (และผ่านตัวกรองคำของ fortune-ai.js) */
  var readName = function (c) { return c.id === "m13" ? "การเปลี่ยนผ่าน" : c.th; };
  var readEn = function (c) { return c.id === "m13" ? "XIII" : c.en; };
  var cardName = function (c) { return readName(c) + " (" + readEn(c) + ") "; };
  /** สำนวนนำตามตำแหน่ง: คืนทุกแบบ (≥ 6) */
  function posLeads(posKey, card, rev) {
    var P = POS_PHRASE[posKey] || ["ในตำแหน่งนี้", "ตรงช่องนี้"], out = [];
    P.forEach(function (p) { POS_FRAME[rev ? "r" : "u"].forEach(function (f) { out.push(fillT(f, { P: p, card: cardName(card) }).replace(/\s{2,}/g, " ")); }); });
    return out;
  }
  function pairKey(a, b) { return a < b ? a + "+" + b : b + "+" + a; }
  /** หมายเหตุคู่ไพ่ (คู่เด่นที่กำหนด หรือไพ่ชุดเดียวกันเลขเรียงกัน) → สำนวน ≥ 3 หรือ null */
  function pairNotes(idA, idB) {
    var k = pairKey(idA, idB), A = KB.byId[idA], B = KB.byId[idB];
    if (PAIRS[k]) return PAIR_FRAME.map(function (f) { return fillT(f, { A: "ไพ่" + readName(A), B: "ไพ่" + readName(B), C: PAIRS[k] }); });
    if (A.suit && A.suit === B.suit && Math.abs(A.n - B.n) === 1 && Math.max(A.n, B.n) <= 10) {
      var lo = A.n < B.n ? A : B, hi = lo === A ? B : A;
      return SEQ_FRAME.map(function (f) { return fillT(f, { A: "ไพ่" + lo.th, B: "ไพ่" + hi.th, Ka: lo.keywords[0], Kb: hi.keywords[0], E: ELEMENTS[lo.element].th, S: SUITS[lo.suit].th }); });
    }
    return null;
  }
  /** รายการคู่ทั้งหมดที่มีหมายเหตุ (คู่เด่น + เลขเรียงกันในชุดเดียวกัน 1–10) */
  function allPairKeys() {
    var keys = Object.keys(PAIRS);
    Object.keys(SUITS).forEach(function (s) { for (var n = 1; n < 10; n++) keys.push(pairKey(s + String(n).padStart(2, "0"), s + String(n + 1).padStart(2, "0"))); });
    return keys;
  }
  function numberNotes(n) { var c = PATTERNS.numberRepeat[n]; return PATTERNS.numberFrame.map(function (f) { return fillT(f, { N: n, C: c }); }); }
  /** เซียมซี: สำนวนต่อหมวด (ข้อความเดิม + 2 สำนวนจากภาพในกลอน) */
  function siamseePhr(s) {
    var T = SS_TPL[s.level], out = {};
    ["meaning", "work", "money", "love", "mind", "travel"].forEach(function (k) {
      out[k] = [s[k]].concat(T[k].map(function (t) { return fillT(t, { I: SS_IMG[s.n], X: s[k] }); }));
    });
    return out;
  }
