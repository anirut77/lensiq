/** split a Markdown table row on unescaped "|" -> trimmed cells ("\|" becomes "|") */
function cells(line) {
  const out = []; let cur = "";
  const s = line.trim().replace(/^\|/, "").replace(/\|$/, "");
  for (let i = 0; i < s.length; i++) {
    if (s[i] === "\\" && s[i + 1] === "|") { cur += "|"; i++; } else if (s[i] === "|") { out.push(cur.trim()); cur = ""; } else cur += s[i];
  }
  out.push(cur.trim());
  return out;
}
const list = c => (c === "—" || c === "" ? [] : c.split(";").map(x => x.trim()).filter(Boolean));

function register() {
  const md = read("docs/ACCURACY-CLAIMS.md");
  const m = md.match(/<!-- claims-register:start -->([\s\S]*?)<!-- claims-register:end -->/);
  assert.ok(m, "register markers in docs/ACCURACY-CLAIMS.md");
  const rows = m[1].split("\n").filter(l => /^\|/.test(l.trim()));
  const head = cells(rows[0]);
  assert.deepEqual(head, ["id", "page", "dict", "key", "sheet", "figures", "n", "labels", "evidence", "quote"]);
  return rows.slice(2).map(l => {
    const c = cells(l); const r = {};
    head.forEach((h, i) => { r[h] = c[i]; });
    return { ...r, figures: list(r.figures), n: list(r.n), labels: list(r.labels), quote: list(r.quote) };
  });
}
/** the original text of a registered claim (snapshot at base, TH / EN / ZH) */
const original = r => SNAP.entries.find(e => e.file === r.page + ".html" && e.key === r.key);

const dicts = new Map();
function dict(lang, base) {
  const k = lang + "-" + base;
  if (!dicts.has(k)) {
    const f = `i18n/${lang}-${base}.js`;
    if (!fs.existsSync(path.join(ROOT, f))) dicts.set(k, {});
    else { const w = {}; w.window = w; vm.runInNewContext(read(f), w); dicts.set(k, Object.assign({}, ...w.LQI18N_Q.map(q => q[lang] || {}))); }
  }
  return dicts.get(k);
}
const reEsc = s => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
/** Thai markup text of the element carrying data-i18n=key */
function thText(html, key) {
  const m = html.match(new RegExp(`<([a-z0-9]+)\\b[^>]*\\bdata-i18n="${reEsc(key)}"[^>]*>([\\s\\S]*?)</\\1>`));
  return m ? squash(unesc(m[2].replace(/<[^>]+>/g, " "))) : null;
}
/** visible text of a page (no comments, scripts, styles, tags) */
const visible = html => squash(unesc(html.replace(/<!--[\s\S]*?-->/g, " ").replace(/<script\b[\s\S]*?<\/script>/gi, " ")
  .replace(/<style\b[\s\S]*?<\/style>/gi, " ").replace(/<[^>]+>/g, " ")));

// old: "register: rows are complete, labels and pages known, evidence still in the source documents"
// new: the same, plus every row names the technical sheet that now carries it, and that sheet holds the original claim
test("register: rows are complete, labels, pages and sheets known, evidence still in the source documents", () => {
  const rows = register();
  assert.ok(rows.length >= 25, "rows: " + rows.length);
  const ids = new Set();
  for (const r of rows) {
    assert.ok(!ids.has(r.id), "duplicate id " + r.id); ids.add(r.id);
    assert.ok(OWNED.includes(r.page), r.id + " page " + r.page);
    assert.equal(r.sheet, SHEET_OF[r.page], r.id + ": sheet of " + r.page);
    for (const l of ["TH", "EN"]) assert.ok(fs.existsSync(path.join(ROOT, `${SHEETS}/${r.sheet}-${l}.md`)), `${r.id}: ${SHEETS}/${r.sheet}-${l}.md`);
    assert.ok(original(r), `${r.id}: ${r.page}.html ${r.key} is in the snapshot`);
    assert.ok(r.labels.some(l => SOURCE_LABELS.includes(l)), r.id + " has a source label");
    r.labels.forEach(l => assert.ok(LABELS[l], `${r.id}: unknown label ${l}`));
    // a claim either has a number with its n, or is explicitly "not measured" (or a dense-crowd statement)
    if (r.figures.length && !r.labels.includes("notmeasured")) assert.ok(r.n.length, r.id + ": a number needs its n");
    if (!r.figures.length) assert.ok(r.labels.includes("notmeasured"), r.id + ": no number -> must say not measured");
    const src = squash(read(r.evidence));
    assert.ok(r.quote.length, r.id + " quotes its evidence");
    r.quote.forEach(q => assert.ok(src.includes(squash(q)), `${r.id}: evidence not found in ${r.evidence}: ${q}`));
    // a figure whose evidence is a tuning set must say "tuning set, optimistic" (ACCURACY-CLAIMS.md section 1)
    if (r.quote.some(q => /tuning/i.test(q)) && r.labels.includes("public")) {
      assert.ok(r.labels.includes("tuning"), r.id + ": evidence is a tuning set -> label 'tuning'");
      if (r.figures.some(f => /85%|\+3\.2%/.test(f))) assert.ok(r.labels.includes("optimistic"), r.id + ": tuning-set headline figure -> 'optimistic'");
    }
  }
});

// old: "the LFW / PETS tuning figures never appear on a page or dictionary without their tuning-set caveat" (+ CASIA first)
// new: in the technical sheets every 85% / +3.2% claim carries its caveat and 13,233 is never n; the held-out CASIA figure
//      still comes before the LFW figure; the pages and dictionaries no longer carry these claims at all
test("the LFW / PETS tuning figures keep their tuning-set caveat in the technical sheets and are gone from the pages", () => {
  const bad = [];
  for (const r of register()) {
    const o = original(r);
    const txt = { th: squash(o.th), en: squash(o.en), zh: squash(o.zh) };
    if (!sheet(r.sheet, "TH").includes(txt.th)) bad.push(`${r.id} th: not in ${r.sheet}-TH.md`);
    for (const lang of ["en", "zh"]) if (!sheet(r.sheet, "EN").includes(txt[lang])) bad.push(`${r.id} ${lang}: not in ${r.sheet}-EN.md`);
    for (const lang of ["th", "en", "zh"]) {
      const t = txt[lang];
      if (/\b85%|\+3\.2%/.test(t) && !(lang === "en" ? t.toLowerCase() : t).includes(LABELS.tuning[lang])) bad.push(`${r.id} ${lang}: ${r.key} without the tuning caveat`);
      if (/n = 13,233/.test(t)) bad.push(`${r.id} ${lang}: 13,233 is the dataset size, not n`);
    }
    const html = read(r.page + ".html"), page = visible(html);
    if (page.includes(txt.th)) bad.push(`${r.id}: ${r.page}.html still shows the claim`);
    for (const lang of ["en", "zh"]) if (Object.values(dict(lang, r.dict)).some(v => squash(v).includes(txt[lang]))) bad.push(`${r.id}: i18n/${lang}-${r.dict}.js still has the claim`);
  }
  assert.deepEqual(bad, []);
  // the held-out CASIA figure is the attendance headline (listed before the LFW figure), in the sheet's original page text
  const att = read(`${SHEETS}/attendance-TH.md`);
  assert.ok(att.indexOf("[attendance.cl2]") > 0 && att.indexOf("[attendance.cl2]") < att.indexOf("[attendance.cl1]"), "CASIA (held out) first");
});

// old: "every registered claim: Thai markup, en and zh carry the number, the n and the source label"
// new: every registered claim in its technical sheet carries the number, the n and the source label (TH sheet: Thai;
//      EN sheet: English and Chinese, no Thai letters); on the page the key, if kept, carries no registered number or n
test("every registered claim: the technical sheet carries the number, the n and the source label; the page carries none", () => {
  const bad = [];
  for (const r of register()) {
    const o = original(r);
    const txt = { th: squash(o.th), en: squash(o.en), zh: squash(o.zh) };
    for (const lang of ["th", "en", "zh"]) {
      const t = txt[lang];
      if (!sheet(r.sheet, lang === "th" ? "TH" : "EN").includes(t)) { bad.push(`${r.id} ${lang}: not in the ${r.sheet} sheet`); continue; }
      if (lang !== "th" && THAI.test(t)) bad.push(`${r.id} ${lang}: Thai letters in ${r.key}`);
      const hay = lang === "en" ? t.toLowerCase() : t;
      for (const f of r.figures.concat(r.n)) if (!t.includes(f)) bad.push(`${r.id} ${lang}: "${f}" missing in ${r.key}: ${t}`);
      for (const l of r.labels) { const w = LABELS[l][lang]; if (!hay.includes(lang === "en" ? w.toLowerCase() : w)) bad.push(`${r.id} ${lang}: label "${w}" missing in ${r.key}`); }
    }
    const page = { th: thText(read(r.page + ".html"), r.key), en: dict("en", r.dict)[r.key], zh: dict("zh", r.dict)[r.key] };
    for (const lang of ["th", "en", "zh"]) {
      const t = page[lang];
      if (t == null) continue;
      for (const f of r.n.concat(r.figures.filter(x => /%/.test(x)))) if (t.includes(f)) bad.push(`${r.id} ${lang}: the page key ${r.key} still shows "${f}"`);
    }
  }
  assert.deepEqual(bad, []);
});

