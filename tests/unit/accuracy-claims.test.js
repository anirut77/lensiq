// moved from the one-pager test: the former accuracy-and-source rows are kept verbatim in the technical sheets, and each
// row still names a source label, keeps the tuning-set caveat on 85% / +3.2%, never uses 13,233 as n, keeps "upper bound"
// and the Asian 92% on the UTKFace row, and gives every percentage its n
test("the former one-pager accuracy rows are in the technical sheets with their labels and caveats", () => {
  const all = fs.readdirSync(path.join(ROOT, SHEETS)).filter(f => f.endsWith(".md")).map(f => squash(read(`${SHEETS}/${f}`))).join("\n");
  const allLabels = SOURCE_LABELS.map(k => LABELS[k]).flatMap(l => [l.th, l.en, l.zh]).concat(["ไม่เกี่ยวข้อง", "不适用", "not applicable"]);
  const rows = SNAP.entries.filter(e => /^docs\/ONE-PAGER-/.test(e.file) && /^\|/.test(e.text.trim())).map(e => ({ e, c: cells(e.text) }))
    .filter(x => x.c.length >= 5 && /\d/.test(x.c[1]));
  assert.ok(rows.length >= 30, "rows: " + rows.length);
  const bad = [];
  for (const { e, c } of rows) {
    const l = e.text.trim(), f = e.file;
    if (!all.includes(squash(e.text))) bad.push(`${f}: row not in ${SHEETS}: ${l.slice(0, 80)}`);
    if (!allLabels.some(w => c[3].toLowerCase().includes(w.toLowerCase()))) bad.push(`${f}: source cell without a label: ${l}`);
    const caveat = /ชุดที่ใช้ปรับค่า|调参|tuning/i.test(c[1] + c[2]) && /ดีเกินจริง|偏乐观|optimistic/i.test(c[1] + c[2]);
    if (/\b85%|\+3\.2%/.test(c[1]) && !caveat) bad.push(`${f}: tuning-set figure without "tuning set, optimistic": ${l}`);
    if (/n = 13,233/.test(c[2])) bad.push(`${f}: 13,233 is the LFW dataset size, not the test set: ${l}`);
    if (/UTKFace/.test(c[2]) && !(/ขอบบน|上限|upper bound/i.test(c[3] + c[1]) && /92%/.test(c[1]))) bad.push(`${f}: UTKFace row needs "upper bound" and Asian 92%: ${l}`);
    if (/\d\s*%/.test(c[1]) && !/งานวิจัยที่ตีพิมพ์|已发表研究|published research|ยังไม่ได้วัด|尚未测量|not measured/i.test(c[3]) && !/n = /.test(c[2])) bad.push(`${f}: a percentage needs its n: ${l}`);
  }
  assert.deepEqual(bad, []);
});
